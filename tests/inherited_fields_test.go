package tests

import "testing"

// A new object gets the initial values of the fields its class's ancestors
// declare (Runtime spec 3.5), each object its own, on tree-walker/bytecode x
// hari/kanade. Regression test for a bug where only the object's own class's
// initializers ran, so inherited fields started as 비어있음 until a method set
// them.
func TestInheritedFieldInitializers(t *testing.T) {
	runTypeCases(t, []typeCase{
		{
			name: "the parent's field starts with its value, in every object",
			hari: `[부모]를 설계하자:
    '값'을 0으로 정하자

    <값넣기>를 만들자 ('새값'):
        '나'의 '값'을 '새값'으로 정하자

[부모]를 바탕으로 [자식]을 설계하자:
    '이름'을 ""로 정하자

'가'를 새로운 [자식]()으로 정하자
'나2'를 새로운 [자식]()으로 정하자
틀"{'가'의 '값'} {'나2'의 '값'}"을 출력하자
'가'의 <값넣기>(5)를 실행하자
틀"{'가'의 '값'} {'나2'의 '값'}"을 출력하자
`,
			kanade: `【親クラス】を設計しよう:
    『値』を0にしよう

    〈値設定〉を作ろう(『新値』):
        私の『値』を『新値』にしよう

【親クラス】をもとにして【子クラス】を設計しよう:
    『名前』を「」にしよう

『甲』を新しい【子クラス】()にしよう
『乙』を新しい【子クラス】()にしよう
枠「{『甲』の『値』} {『乙』の『値』}」を出力しよう
『甲』の〈値設定〉(5)を実行しよう
枠「{『甲』の『値』} {『乙』の『値』}」を出力しよう
`,
			want: "0 0|5 0",
		},
		{
			name: "a hidden inherited field set to an object by a parent method",
			hari: `[칸]을 설계하자:
    '다음'을 비어있음으로 정하여 숨기자

    [칸]을 돌려주는 <다음은>을 만들자 ([칸]인 '누구'):
        '나'의 '다음'을 '누구'로 정하자
        '누구'를 돌려주자

    <비었나>를 만들자 ():
        ('나'의 '다음'이 비어있음과 같다)를 출력하자

[칸]을 바탕으로 [빨간칸]을 설계하자:
    <색>을 만들자 ():
        "빨강"을 출력하자

'가'를 새로운 [빨간칸]()으로 정하자
'나2'를 새로운 [빨간칸]()으로 정하자
'가'의 <다음은>('나2')를 실행하자
'가'의 <비었나>()를 실행하자
'나2'의 <비었나>()를 실행하자
`,
			kanade: `【マス】を設計しよう:
    『次』を空っぽに隠そう

    【マス】を返す〈次は〉を作ろう(【マス】の『誰』):
        私の『次』を『誰』にしよう
        『誰』を返そう

    〈空か〉を作ろう():
        (私の『次』が空っぽと同じ)を出力しよう

【マス】をもとにして【赤マス】を設計しよう:
    〈色〉を作ろう():
        「赤」を出力しよう

『甲』を新しい【赤マス】()にしよう
『乙』を新しい【赤マス】()にしよう
『甲』の〈次は〉(『乙』)を実行しよう
『甲』の〈空か〉()を実行しよう
『乙』の〈空か〉()を実行しよう
`,
			want: "거짓|참", wantKanade: "偽|真",
		},
		{
			name: "three levels: own lists, the child's value wins, before the constructors",
			hari: `[할아버지]를 설계하자:
    '목록'을 []로 정하자
    '이름'을 "할아버지"로 정하자
    '비밀'을 7로 정하여 숨기자
    '가보'를 "족보"로 정하여 물려주자
    <비밀>을 만들자 ():
        '나'의 '비밀'을 돌려주자

[할아버지]를 바탕으로 [아버지]를 설계하자:
    '이름'을 "아버지"로 정하자
    '나이'를 40으로 정하자
    처음 만들어질 때 () 다음과 같이 하자:
        틀"생성자: {'나'의 '이름'} {'나'의 '나이'}"를 출력하자
        '나'의 '나이'를 41로 정하자

[아버지]를 바탕으로 [아들]을 설계하자:
    '나이'를 10으로 정하자
    <가보>를 만들자 ():
        '나'의 '가보'를 돌려주자

'a'를 새로운 [아들]()로 정하자
'b'를 새로운 [아들]()로 정하자
'a'의 '목록' 뒤에 1을 추가하자
틀"{'a'의 '목록'} {'b'의 '목록'} {'a'의 '나이'} {'a'의 <비밀>()} {'a'의 <가보>()}"를 출력하자
`,
			kanade: `【祖父】を設計しよう:
    『リスト』を【】にしよう
    『名前』を「祖父」にしよう
    『秘密』を7に隠そう
    『家宝』を「家系図」に譲ろう
    〈秘密〉を作ろう():
        私の『秘密』を返そう

【祖父】をもとにして【父】を設計しよう:
    『名前』を「父」にしよう
    『年齢』を40にしよう
    最初に作られる時 () 次のようにしよう:
        枠「コンストラクタ:{私の『名前』} {私の『年齢』}」を出力しよう
        私の『年齢』を41にしよう

【父】をもとにして【息子】を設計しよう:
    『年齢』を10にしよう
    〈家宝〉を作ろう():
        私の『家宝』を返そう

『a』を新しい【息子】()にしよう
『b』を新しい【息子】()にしよう
『a』の『リスト』の後ろに1を追加しよう
枠「{『a』の『リスト』} {『b』の『リスト』} {『a』の『年齢』} {『a』の〈秘密〉()} {『a』の〈家宝〉()}」を出力しよう
`,
			want:       "생성자: 아버지 10|생성자: 아버지 10|[1] [] 41 7 족보",
			wantKanade: "コンストラクタ:父 10|コンストラクタ:父 10|[1] [] 41 7 家系図",
		},
		{
			name:    "an inherited hidden field is still hidden from outside",
			hari:    "[가]를 설계하자:\n    '비밀'을 7로 정하여 숨기자\n[가]를 바탕으로 [나라]를 설계하자:\n    '공개'를 1로 정하자\n'x'를 새로운 [나라]()로 정하자\n('x'의 '공개')를 출력하자\n('x'의 '비밀')을 출력하자\n",
			kanade:  "【甲】を設計しよう:\n    『秘密』を7に隠そう\n【甲】をもとにして【乙】を設計しよう:\n    『公開』を1にしよう\n『x』を新しい【乙】()にしよう\n(『x』の『公開』)を出力しよう\n(『x』の『秘密』)を出力しよう\n",
			wantErr: "private",
		},
	})
}
